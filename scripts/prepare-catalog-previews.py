"""Package static catalogue thumbnails for web, Android and desktop builds.

Run with the backend Pillow dependency installed. Originals are never modified.
Content-hashed filenames make updated bundles safe to cache across releases.
"""
import hashlib
import json
import importlib.util
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
output = root / 'frontend/public/assets/catalog-previews'
output.mkdir(parents=True, exist_ok=True)
sources = {p.stem: p for p in (root/'backend/app/assets/collectibles').iterdir()
           if p.suffix.lower() in ('.png', '.webp', '.jpg')}
for manifest in (root/'backend/catalog').rglob('*.json'):
    data = json.loads(manifest.read_text(encoding='utf8'))
    if not isinstance(data, dict) or not isinstance(data.get('items'), list):
        continue
    for item in data['items']:
        source = manifest.parent / (item['slug']+'.webp')
        if source.is_file():
            sources[item['id']] = source
mapping = {}
for key, source in sorted(sources.items()):
    with Image.open(source) as original:
        original.seek(0)
        image = ImageOps.exif_transpose(original).convert('RGBA')
        image.thumbnail((256, 256), Image.Resampling.LANCZOS)
        buffer = BytesIO()
        image.save(buffer, 'WEBP', quality=76, method=4)
    content = buffer.getvalue()
    name = hashlib.sha256(content).hexdigest()[:24]+'.webp'
    (output/name).write_bytes(content)
    mapping[key] = name
spec = importlib.util.spec_from_file_location('catalog_themes', root/'backend/app/services/themes.py')
themes = importlib.util.module_from_spec(spec)
spec.loader.exec_module(themes)
for key in themes.THEMES:
    content = themes.theme_svg(key).encode()
    name = hashlib.sha256(content).hexdigest()[:24]+'.svg'
    (output/name).write_bytes(content)
    mapping[key] = name
with Image.open(root/'backend/app/assets/avatars/cat.webp') as image:
    image.thumbnail((256,256),Image.Resampling.LANCZOS)
    image.save(output.parent/'avatar-fallback.webp','WEBP',quality=76)
manifest = json.dumps(mapping, indent=2)+'\n'
(output/'manifest.json').write_text(manifest, encoding='utf8')
version = hashlib.sha256(manifest.encode()).hexdigest()[:16]
(root/'frontend/src/app/core/services/catalog-preview-version.ts').write_text(
    '// Generated by scripts/prepare-catalog-previews.py\n'
    f"export const CATALOG_PREVIEW_VERSION = '{version}';\n", encoding='utf8')
print(len(mapping), 'bundled thumbnails;', sum((output/n).stat().st_size for n in set(mapping.values())), 'bytes')
