const {_electron: electron} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
let profile = fs.mkdtempSync(path.join(os.tmpdir(), 'kva-desktop-smoke-'));
let instance;
(async () => {
  const env={...process.env,KVA_DESKTOP_TEST:'1',KVA_DESKTOP_PROFILE:profile};delete env.ELECTRON_RUN_AS_NODE;
  instance = await electron.launch({...(process.env.KVA_SMOKE_EXE?{executablePath:process.env.KVA_SMOKE_EXE,args:['--user-data-dir='+profile]}:{args:[root]}),env,timeout:60000});
  assert.equal(await instance.evaluate(({app})=>app.getPath('userData')),profile,'Must use an isolated empty profile');
  const page = await instance.firstWindow();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.getByLabel('Email',{exact:true}).waitFor({timeout:60000});
  assert.equal(page.url(),'https://kvachat.ru/');
  const health=await page.evaluate(async()=>{const r=await fetch('/api/health');return {status:r.status,body:await r.json()};});
  assert.equal(health.status,200);assert.equal(health.body.database,'online');
  assert.equal(await page.evaluate(()=>typeof window.require),'undefined');
  assert.equal(await page.evaluate(()=>window.kvaDesktop.version),require('../package.json').version);
  const sample=JSON.stringify({access_token:'local-smoke-token',user:{id:'smoke'}});
  assert(!fs.existsSync(path.join(profile,'session.bin')), 'Use an empty test profile; never overwrite an existing session');
  assert.equal(await page.evaluate(value=>window.kvaDesktop.writeSession(value),sample),true);
  assert.equal(await page.evaluate(()=>window.kvaDesktop.readSession()),sample);
  assert(!fs.readFileSync(path.join(profile,'session.bin')).includes(Buffer.from('local-smoke-token')));
  assert.equal(await page.evaluate(()=>localStorage.getItem('tescord.session')),null);
  await page.evaluate(()=>window.kvaDesktop.writeSession(null));
  assert(!fs.existsSync(path.join(profile,'session.bin')));
  const image=await page.locator('app-guest-header img').evaluate(img=>({loaded:img.complete&&img.naturalWidth>0}));assert(image.loaded);
  // Show the real capture chooser, then cancel without granting any source.
  await instance.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0,checkboxChecked:false});});
  const pickerPromise=instance.waitForEvent('window',{timeout:20000});
  await page.evaluate(()=>{window.captureTest=navigator.mediaDevices.getDisplayMedia({video:true,audio:true}).then(s=>{s.getTracks().forEach(t=>t.stop());return 'granted';}).catch(e=>e.name);});
  const picker=await pickerPromise;
  await picker.locator('#sources button').first().waitFor({timeout:20000});
  await picker.screenshot({path:path.join(profile,'capture-picker.png')});
  await picker.getByRole('button',{name:'Отмена',exact:true}).click({noWaitAfter:true});
  assert.notEqual(await page.evaluate(()=>window.captureTest),'granted');
  await instance.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.restore();w.show();w.focus();});
  await page.bringToFront();
  await page.screenshot({path:path.join(profile,'login.png')});
  await instance.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
  assert.equal(await instance.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,profile,health:health.body,checks:['bundled UI','production API','sandbox','DPAPI session','capture cancellation','tray close']}));
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(instance)await instance.close();});
